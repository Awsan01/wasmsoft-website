/**
 * Generates resources/js/lib/icons.ts from resources/icons/lucide.php, so the
 * React interface and the Blade error pages draw from the same curated set.
 *
 * Run after adding or changing an icon in lucide.php:
 *
 *     npm run icons
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const source = readFileSync(`${root}resources/icons/lucide.php`, 'utf8');
const iconComponent = readFileSync(`${root}app/View/Components/Ui/Icon.php`, 'utf8');

/** Icons mirrored in right-to-left layouts, read from App\View\Components\Ui\Icon::DIRECTIONAL. */
const directional = [...(/DIRECTIONAL = \[([^\]]*)\]/.exec(iconComponent)?.[1] ?? '').matchAll(/'([a-z0-9-]+)'/g)].map((match) => match[1]);

const camel = (name) => name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());

const icons = [...source.matchAll(/^\s*'([a-z0-9-]+)' => '(.*)',$/gm)].map(([, name, markup]) => {
    const nodes = [...markup.matchAll(/<([a-z]+)\s+([^>]*?)\s*\/>/g)].map(([, tag, attributes]) => {
        const props = Object.fromEntries([...attributes.matchAll(/([a-zA-Z][a-zA-Z0-9-]*)="([^"]*)"/g)].map(([, key, value]) => [camel(key), value]));

        if (Object.keys(props).length === 0) {
            throw new Error(`Icon "${name}" has a <${tag}> without attributes.`);
        }

        return [tag, props];
    });

    if (nodes.length === 0) {
        throw new Error(`Icon "${name}" has no drawable elements.`);
    }

    return [name, nodes];
});

const missing = directional.filter((name) => !icons.some(([icon]) => icon === name));
if (missing.length > 0) {
    throw new Error(`Directional icons missing from lucide.php: ${missing.join(', ')}`);
}

const lines = icons.map(([name, nodes]) => `    '${name}': ${JSON.stringify(nodes)},`);

writeFileSync(
    `${root}resources/js/lib/icons.ts`,
    `// Generated by scripts/generate-icons.mjs from resources/icons/lucide.php. Do not edit by hand.
// Lucide (https://lucide.dev), ISC License. Portions of Lucide are copyright Cole Bemis 2013-2022
// as part of Feather (MIT); all other copyright for Lucide is held by Lucide Contributors 2022.
// The "x-logo" glyph is from Simple Icons (CC0 1.0) and is filled, not stroked.

export type IconNode = readonly [tag: string, attributes: Readonly<Record<string, string>>];

export const icons = {
${lines.join('\n')}
} as const satisfies Record<string, readonly IconNode[]>;

export type IconName = keyof typeof icons;

/** Icons whose meaning depends on reading direction; mirrored in right-to-left layouts. */
export const directionalIcons: ReadonlySet<IconName> = new Set<IconName>(${JSON.stringify(directional)});
`,
);

console.log(`resources/js/lib/icons.ts: ${icons.length} icons (${directional.length} directional)`);
